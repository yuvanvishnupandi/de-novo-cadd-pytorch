"""
EUREKA: AutoDock 4.2 Grid Parameter File (GPF) & Docking Parameter File (DPF) Writer
Generates complete .gpf and .dpf input scripts for AutoGrid 4.2 and AutoDock 4.2 / Vina,
including atom type dielectric grids, desolvation parameter maps, and LGA state definitions.

Strictly Computational Chemistry & Script Generation. Zero Agentic AI.
"""

from typing import List, Dict, Tuple, Any, Optional


class AutoDockParameterFileWriter:
    """
    Constructs compliant AutoGrid .gpf and AutoDock .dpf parameter files.
    """

    @staticmethod
    def write_gpf(receptor_pdbqt_filename: str,
                  grid_center: Tuple[float, float, float],
                  grid_points: Tuple[int, int, int],
                  spacing: float = 0.375,
                  ligand_types: Optional[List[str]] = None) -> str:
        """
        Generates standard AutoGrid 4.2 .gpf script.
        """
        if ligand_types is None:
            ligand_types = ["C", "A", "N", "NA", "OA", "F", "Cl", "S", "HD"]

        types_str = " ".join(ligand_types)
        cx, cy, cz = grid_center
        nx, ny, nz = grid_points

        lines = [
            f"# AutoGrid 4.2 Grid Parameter File (GPF)",
            f"# Generated by EUREKA In-Silico Biophysics Workbench",
            f"npts {nx} {ny} {nz}                        # num.grid points in xyz",
            f"gridfld {receptor_pdbqt_filename}.maps.fld # grid_data_file",
            f"spacing {spacing:.3f}                      # spacing(A)",
            f"receptor_types A C H HD N NA OA SA S       # receptor atom types",
            f"ligand_types {types_str}                   # ligand atom types",
            f"receptor {receptor_pdbqt_filename}         # macromolecule",
            f"gridcenter {cx:.3f} {cy:.3f} {cz:.3f}      # xyz-coordinates or auto",
            f"smooth 0.500                               # store minimum energy if within radius",
            f"dielectric -0.1465                         # <0, AD4 distance-dep.dielectric"
        ]

        for lt in ligand_types:
            lines.append(f"map {receptor_pdbqt_filename}.{lt}.map")
        lines.append(f"map {receptor_pdbqt_filename}.e.map")
        lines.append(f"map {receptor_pdbqt_filename}.d.map")

        return "\n".join(lines) + "\n"

    @staticmethod
    def write_dpf(receptor_pdbqt_filename: str,
                  ligand_pdbqt_filename: str,
                  num_ga_runs: int = 10,
                  pop_size: int = 150,
                  max_evals: int = 2500000) -> str:
        """
        Generates standard AutoDock 4.2 .dpf script with Lamarckian Genetic Algorithm parameters.
        """
        lines = [
            f"# AutoDock 4.2 Docking Parameter File (DPF)",
            f"# Generated by EUREKA In-Silico Biophysics Workbench",
            f"autodock_parameter_version 4.2",
            f"outlev 1",
            f"seed pid time",
            f"ligand_types C A N OA F Cl S HD",
            f"fld {receptor_pdbqt_filename}.maps.fld",
            f"move {ligand_pdbqt_filename}",
            f"about 0.0 0.0 0.0",
            f"tran0 random",
            f"quaternion0 random",
            f"dihe0 random",
            f"torsdof 6",
            f"rmstol 2.0",
            f"ga_run {num_ga_runs}",
            f"ga_pop_size {pop_size}",
            f"ga_num_evals {max_evals}",
            f"ga_num_generations 27000",
            f"ga_elitism 1",
            f"ga_mutation_rate 0.02",
            f"ga_crossover_rate 0.80",
            f"ga_window_size 10",
            f"ga_cauchy_alpha 0.0",
            f"ga_cauchy_beta 1.0",
            f"set_sw1",
            f"sw_max_its 300",
            f"sw_rate 0.06",
            f"docking"
        ]
        return "\n".join(lines) + "\n"

