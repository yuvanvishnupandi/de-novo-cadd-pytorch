"""
AutoGrid 4 (GPF) and AutoDock 4 (DPF) Parameter File Generation and Grid Parameter Engine.

Generates validated docking input files for AutoGrid and AutoDock:
- Grid Parameter File (.gpf) generation:
  - gridcenter x, y, z
  - npts (nx, ny, nz) grid points with standard 0.375 Angstrom spacing
  - atom types dictionary: ligand_types, receptor_types
  - dielectric constant and distance-dependent dielectric (epsilon(r))
  - pairwise affinity grid maps (.map) for C, A, N, NA, OA, S, SA, Cl, F, e, d
- Docking Parameter File (.dpf) generation:
  - Lamarckian Genetic Algorithm (LGA) parameter configuration:
    - ga_pop_size = 150
    - ga_num_evals = 2,500,000 (standard) to 25,000,000 (rigorous)
    - ga_num_generations = 27,000
    - ga_elitism = 1
    - ga_mutation_rate = 0.02
    - ga_crossover_rate = 0.80
    - ga_window_size = 10
    - Solis-Wets local search: sw_max_its = 300, sw_max_succ = 4, sw_max_fail = 4, sw_rho = 1.0
  - Cluster analysis: rmsd_tolerance = 2.0 Angstroms.
"""

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple, Any
import math


@dataclass
class AutoGridBoxSpecification:
    center_x: float
    center_y: float
    center_z: float
    size_x_angstroms: float
    size_y_angstroms: float
    size_z_angstroms: float
    spacing_angstroms: float = 0.375

    @property
    def npts_x(self) -> int:
        """Even integer number of grid intervals."""
        n = int(round(self.size_x_angstroms / self.spacing_angstroms))
        return n if n % 2 == 0 else n + 1

    @property
    def npts_y(self) -> int:
        n = int(round(self.size_y_angstroms / self.spacing_angstroms))
        return n if n % 2 == 0 else n + 1

    @property
    def npts_z(self) -> int:
        n = int(round(self.size_z_angstroms / self.spacing_angstroms))
        return n if n % 2 == 0 else n + 1


class AutoDockGPFDPFGenerator:
    """
    Automated generator for classical AutoGrid 4 (.gpf) and AutoDock 4 (.dpf) control files.
    """

    DEFAULT_LIGAND_TYPES = ["C", "A", "N", "NA", "OA", "HD", "F", "Cl"]
    DEFAULT_RECEPTOR_TYPES = ["C", "A", "N", "NA", "OA", "SA", "HD"]

    def __init__(self, receptor_pdbqt: str, ligand_pdbqt: str, box: AutoGridBoxSpecification):
        self.receptor_file = receptor_pdbqt
        self.ligand_file = ligand_pdbqt
        self.box = box

    def generate_gpf_content(self, ligand_types: Optional[List[str]] = None) -> str:
        """Constructs complete AutoGrid 4 .gpf parameter text."""
        types = ligand_types or self.DEFAULT_LIGAND_TYPES
        types_str = " ".join(types)

        lines = [
            f"; AutoGrid 4 Grid Parameter File generated by Eureka Biophysics Engine",
            f"; Target Receptor: {self.receptor_file}",
            f"; Ligand Lead: {self.ligand_file}",
            f"",
            f"npts {self.box.npts_x} {self.box.npts_y} {self.box.npts_z}   # num.grid points in x,y,z",
            f"gridfld {self.receptor_file}.maps.fld    # grid_data_file",
            f"spacing {self.box.spacing_angstroms:.3f}                      # spacing(A)",
            f"receptor_types {' '.join(self.DEFAULT_RECEPTOR_TYPES)}        # receptor atom types",
            f"ligand_types {types_str}              # ligand atom types",
            f"receptor {self.receptor_file}                         # macromolecule",
            f"gridcenter {self.box.center_x:.3f} {self.box.center_y:.3f} {self.box.center_z:.3f}   # xyz-coordinates or auto",
            f"smooth 0.500                              # store minimum energy if within distance",
        ]

        for t in types:
            lines.append(f"map {self.receptor_file}.{t}.map               # atom-specific affinity map")

        lines.extend([
            f"elecmap {self.receptor_file}.e.map               # electrostatics map",
            f"dsolvmap {self.receptor_file}.d.map              # desolvation map",
            f"dielectric -0.1465                         # <0, AD4 distance-dep.di-electric;>0, constant",
        ])

        return "\n".join(lines)

    def generate_dpf_content(
        self,
        ga_runs: int = 50,
        ga_evals: int = 2500000,
        rmsd_cluster_tol: float = 2.0
    ) -> str:
        """Constructs complete AutoDock 4 .dpf parameter text with Lamarckian Genetic Algorithm."""
        types_str = " ".join(self.DEFAULT_LIGAND_TYPES)

        lines = [
            f"; AutoDock 4 Docking Parameter File generated by Eureka Biophysics Engine",
            f"; Algorithm: Lamarckian Genetic Algorithm (LGA)",
            f"",
            f"autodock_parameter_version 4.2           # parameters version",
            f"outlev 1                                  # diagnostic output level",
            f"intelec                                    # calculate internal electrostatics",
            f"seed pid time                             # seeds for random number generator",
            f"ligand_types {types_str}                 # ligand atom types",
            f"fld {self.receptor_file}.maps.fld        # grid_data_file",
        ]

        for t in self.DEFAULT_LIGAND_TYPES:
            lines.append(f"map {self.receptor_file}.{t}.map")

        lines.extend([
            f"elecmap {self.receptor_file}.e.map",
            f"dsolvmap {self.receptor_file}.d.map",
            f"move {self.ligand_file}",
            f"about 0.0 0.0 0.0                          # small molecule center",
            f"tran0 random                              # initial coordinates/orientation or random",
            f"quaternion0 random",
            f"dihe0 random",
            f"",
            f"; Lamarckian Genetic Algorithm Parameters",
            f"ga_pop_size 150                           # number of individuals in population",
            f"ga_num_evals {ga_evals}                  # maximum number of energy evaluations",
            f"ga_num_generations 27000                  # maximum number of generations",
            f"ga_elitism 1                              # number of top individuals to survive to next gen",
            f"ga_mutation_rate 0.02                     # rate of gene mutation",
            f"ga_crossover_rate 0.80                    # rate of crossover",
            f"ga_window_size 10                         # window size for generational history",
            f"ga_cauchy_alpha 0.0                       # alpha parameter of Cauchy distribution",
            f"ga_cauchy_beta 1.0                        # beta parameter Cauchy distribution",
            f"",
            f"; Solis and Wets Local Search Parameters",
            f"sw_max_its 300                            # iterations of Solis & Wets local search",
            f"sw_max_succ 4                             # consecutive successes before changing rho",
            f"sw_max_fail 4                             # consecutive failures before changing rho",
            f"sw_rho 1.0                                # size of local search space",
            f"sw_lb_rho 0.01                            # lower bound on rho",
            f"ls_search_freq 0.06                       # probability of performing local search on individual",
            f"",
            f"; Clustering Parameters",
            f"set_ga                                    # set the above parameters for GA or LGA",
            f"ga_run {ga_runs}                          # number of LGA runs",
            f"analysis                                  # perform cluster analysis",
            f"rmsref 0.0 0.0 0.0                        # calculate RMSD from reference coordinates",
            f"cluster_tolerance {rmsd_cluster_tol:.1f}                  # RMSD tolerance for cluster clustering",
        ])

        return "\n".join(lines)

